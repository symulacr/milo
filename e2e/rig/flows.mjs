/**
 * B1 flow inventory for e2e/rig.
 *
 * One entry per flow, each with an ID that Wave 3, 4 and 7 can reference, a
 * goal, a start state, machine-checkable success criteria and a negative or
 * edge twin. The IDs are the contract: they never change meaning, they are
 * only ever added to.
 *
 * Sources this inventory was derived from, read in full:
 *   apps/web/src/route-table.ts          the two route lists and the prefixes
 *   apps/web/src/App.tsx                 the workspace route tree
 *   apps/web/src/public-main.tsx         the public route tree
 *   apps/web/src/shells/*.tsx            skip link, nav, scenario toolbar
 *   apps/web/src/routes/*.tsx            one component per surface
 *   apps/web/src/components/*.tsx        action panel, dialog, payment panel
 *   apps/web/src/workspace/model.tsx     scenarios, roles, action labels
 *   packages/domain/src/prototype.ts     phases, payments, transition rules
 *   apps/web/index.html app.html public-app.html   the three entrypoints
 *   apps/web/src/RecoveryKitPanel.tsx    recovery-kit and reserve surfaces
 *
 * Steps use Playwright selector syntax so the catalog stays readable and the
 * executor stays dumb.
 */

