export const FLOWS_BY_ID = new Map(FLOW_CATALOG.map((entry) => [entry.id, entry]));

export function selectFlows(ids) {
  if (!ids || ids.length === 0) return FLOW_CATALOG;
  const unknown = ids.filter((id) => !FLOWS_BY_ID.has(id));
  if (unknown.length > 0) {
    throw new Error(
      `Unknown flow id(s): ${unknown.join(", ")}. Run with --list to see all ${FLOW_CATALOG.length}.`,
    );
  }
  return ids.map((id) => FLOWS_BY_ID.get(id));
}

/** Declared click cost, derived from the steps so the CSV never drifts. */
export function declaredCost(flowEntry) {
  let clicks = 0;
  let fields = 0;
  let keys = 0;
  for (const step of flowEntry.steps) {
    if (step.click) clicks += 1;
    if (step.check || step.uncheck) clicks += 1;
    if (step.fill) fields += 1;
    if (step.select) fields += 1;
    if (step.press) keys += step.times ?? 1;
    if (step.markGoal) break;
  }
  return { clicks, fields, keys };
}

